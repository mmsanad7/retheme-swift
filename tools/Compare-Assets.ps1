<#
.SYNOPSIS
  Compares sourceDir and outputDir by content hash and writes a Markdown report
  (counts + full changed/unchanged lists). Also verifies names/structure are identical.

.EXAMPLE
  .\tools\Compare-Assets.ps1 -Project excp-swift-demo
  .\tools\Compare-Assets.ps1 -Project excp-swift-demo -OutFile docs\projects\excp-swift-demo\changed-files.md
#>
param(
    [Parameter(Mandatory = $true)][string]$Project,
    [string]$OutFile
)
. (Join-Path $PSScriptRoot '_common.ps1')
$cfg = Get-RethemeConfig $Project
$src = $cfg._source; $dst = $cfg._output

function Get-Rel($root) {
    Get-ChildItem $root -Recurse -File | ForEach-Object { $_.FullName.Substring($root.Length).TrimStart('\') -replace '\\', '/' } | Sort-Object
}
$a = @(Get-Rel $src); $b = @(Get-Rel $dst)
$missing = @($a | Where-Object { $b -notcontains $_ }); $extra = @($b | Where-Object { $a -notcontains $_ })

$changed = @(); $same = @()
foreach ($r in $a) {
    if ($b -notcontains $r) { continue }
    $h1 = (Get-FileHash (Join-Path $src $r)).Hash; $h2 = (Get-FileHash (Join-Path $dst $r)).Hash
    if ($h1 -ne $h2) { $changed += $r } else { $same += $r }
}
function Get-Kind($r) {
    switch -regex ($r) { '\.svg$' { 'SVG' } '\.(png|jpe?g|webp|gif)$' { 'Raster' } '\.(ttf|otf)$' { 'Font' } default { 'Other' } }
}
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# Changed files report - $($cfg.name)")
[void]$sb.AppendLine('')
[void]$sb.AppendLine("> Generated by ``tools/Compare-Assets.ps1`` on $(Get-Date -Format 'yyyy-MM-dd'). Do not edit by hand.")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| | Count |'); [void]$sb.AppendLine('|---|---|')
[void]$sb.AppendLine("| Total files (source) | $($a.Count) |")
[void]$sb.AppendLine("| Changed | $($changed.Count) |")
[void]$sb.AppendLine("| Unchanged | $($same.Count) |")
[void]$sb.AppendLine("| Missing in output | $($missing.Count) |")
[void]$sb.AppendLine("| Extra in output | $($extra.Count) |")
foreach ($k in 'SVG', 'Raster', 'Font', 'Other') {
    $c = @($changed | Where-Object { (Get-Kind $_) -eq $k }).Count; $u = @($same | Where-Object { (Get-Kind $_) -eq $k }).Count
    [void]$sb.AppendLine("| $k : changed / unchanged | $c / $u |")
}
[void]$sb.AppendLine(''); [void]$sb.AppendLine("## Changed ($($changed.Count))"); [void]$sb.AppendLine('')
$changed | ForEach-Object { [void]$sb.AppendLine("- ``$_``") }
[void]$sb.AppendLine(''); [void]$sb.AppendLine("## Unchanged ($($same.Count))"); [void]$sb.AppendLine('')
$same | ForEach-Object { [void]$sb.AppendLine("- ``$_``") }
if ($missing.Count -or $extra.Count) {
    [void]$sb.AppendLine(''); [void]$sb.AppendLine('## Structure problems'); [void]$sb.AppendLine('')
    $missing | ForEach-Object { [void]$sb.AppendLine("- missing: ``$_``") }
    $extra | ForEach-Object { [void]$sb.AppendLine("- extra: ``$_``") }
}
$report = $sb.ToString()
if ($OutFile) { Write-Utf8 ([IO.Path]::GetFullPath((Join-Path (Get-Location) $OutFile))) $report; Write-Output "Report written: $OutFile" }
Write-Output ("Total {0} | changed {1} | unchanged {2} | missing {3} | extra {4}" -f $a.Count, $changed.Count, $same.Count, $missing.Count, $extra.Count)
if ($missing.Count -or $extra.Count) { Write-Warning 'File names/structure differ between source and output!' }
